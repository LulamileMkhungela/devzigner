function shellFile(project: Project): string {
  const nav = project.system.shell.nav.map((n) => n.label)
  return `// Generated by Lula DevZign — the AppShell skeleton.
// Pages are assembled only from the component registry (see system/registry.md).
// Nav labels, content width and card style come from the compiled design tokens.

import type { ReactNode } from 'react'

const NAV = ${JSON.stringify(nav, null, 2)}

export function AppShell({ current, children }: { current: string; children: ReactNode }) {
  return (
    <div className="shell" data-shell="${project.design.layout.shell}">
      <aside className="shell-rail" aria-label="${project.name}">
        <span className="shell-brand">${project.name.slice(0, 1).toUpperCase()}</span>
        <nav>
          {NAV.map((label) => (
            <a key={label} href={'#/' + label.toLowerCase().replace(/\\s+/g, '-')} aria-current={label === current ? 'page' : undefined}>
              {label}
            </a>
          ))}
        </nav>
      </aside>
      <main className="shell-main" style={{ maxWidth: ${project.design.layout.contentWidth} }}>
        {children}
      </main>
    </div>
  )
}
`
}

function registryJson(project: Project): string {
  return JSON.stringify(
    {
      generatedBy: 'Lula DevZign',
      product: project.name,
      components: project.system.components,
      note: 'Components may only use the tokens listed against them.',
    },
    null,
    2,
  )
}

export function buildSystemFiles(project: Project, versions: Version[] = []): PackageFile[] {
  const files: PackageFile[] = []
  const wiki = buildWiki(project)

  files.push({ path: 'flows.md', content: wiki.find((w) => w.slug === 'flows')?.body ?? '# Flows\n' })
  files.push({ path: 'system/stack.md', content: wiki.find((w) => w.slug === 'stack')?.body ?? '# Stack\n' })
  files.push({ path: 'system/registry.md', content: wiki.find((w) => w.slug === 'components')?.body ?? '# Registry\n' })
  files.push({ path: 'system/registry.json', content: registryJson(project) })
  files.push({ path: 'system/app-shell.md', content: wiki.find((w) => w.slug === 'app-shell')?.body ?? '# Shell\n' })
  files.push({ path: 'system/data-layer.md', content: wiki.find((w) => w.slug === 'data-layer')?.body ?? '# Data\n' })

  files.push({ path: 'src/components/app-shell.tsx', content: shellFile(project) })
  files.push({ path: 'src/data/types.ts', content: typesFile(project) })
  files.push({ path: 'src/data/repository.ts', content: repositoryFile(project) })
  files.push({ path: 'src/data/mock-adapter.ts', content: mockFile(project) })

  files.push({
    path: 'wiki/README.md',
    content: `# ${project.name} — prototype wiki\n\nThis folder is the product and design knowledge for the prototype. It is generated, versioned and safe to commit next to the code.\n\n${wiki
      .map((w) => `- [${w.title}](./${w.slug}.md) — ${w.summary}`)
      .join('\n')}\n\n## Branches\n\nPrototype iterations live on branches. See [CHANGELOG.md](./CHANGELOG.md). A worktree per branch keeps the wiki and the code moving together:\n\n\`\`\`bash\ngit worktree add ../${project.id}-explore explorer\n\`\`\`\n`,
  })
  for (const entry of wiki) files.push({ path: `wiki/${entry.slug}.md`, content: entry.body + '\n' })
  files.push({ path: 'wiki/CHANGELOG.md', content: versionsMarkdown(project, versions) })

  return files
}

export function entityShape(entity: Entity): string {
  return `${entity.name}: ${entity.fields.length} fields, ${entity.rows.length} seeded rows`
}
