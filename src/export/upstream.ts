/**
 * The five upstream repositories ProdOps is built on, reviewed and pinned.
 *
 * Everything ProdOps installs from Builder Methods is vendored *verbatim* —
 * `src/export/vendor/` holds the command files, the four bm-skills, the two
 * agentcanon skills and the Build New starter notes exactly as upstream ships
 * them. That is a claim about a moving target, so it is pinned: this file
 * records what was reviewed, at which commit, and what was compared. Two
 * things then hold it honest:
 *
 *   - `npm run upstream-check` re-downloads each repo and diffs every vendored
 *     file against it, failing on any drift;
 *   - `UPSTREAM-REVIEW.md` in this repo (generated by `npm run upstream-doc`)
 *     states the result for someone reading the code, not running it.
 *
 * The `shipped` lists are the reviewer's summary of what ProdOps installs from
 * each repo; the `gaps` lists are things upstream has that ProdOps deliberately
 * does not, stated so nobody has to guess.
 */

export interface UpstreamReview {
  repo: string
  url: string
  /** `main` at the time of review. Pin it: "latest" is not a review. */
  commit: string
  commitDate: string
  reviewedOn: string
  purpose: string
  /** Vendored into the package, with the path prefix it lands under. */
  shipped: { what: string; where: string; count?: number }[]
  /** Present upstream and not shipped, with the reason. */
  gaps: { what: string; why: string }[]
  /** Checked by machine, not by eye. */
  verified: string[]
}

