// ProdOps — developed by Lulamike Mkhungela.
//
// Documents: every role step writes real markdown — a spec, a process, a
// roadmap or a note — from the project's own compiled data plus the answers
// the builder gave to the step's clarifying questions. Nothing is invented: if
// a section has no requirements, the document says so instead of making them up.
//
// This is the "save the spec into the spec folder" half of the roles: the
// generators are pure, so the workspace saves one on a click and the export
// writes the same file into `spec/<role>/` without a second source of truth.

import type { Project } from '../types'
import {
  answerKey,
  roleArtifacts,
  roleById,
  stepReview,
  type Deliverable,
  type RoleDef,
  type RoleStep,
} from './roles'

/* ------------------------------------------------------------- primitives -- */

function list(items: string[]): string {
  return items.length ? items.map((item) => `- ${item}`).join('\n') : '- _None yet._'
}

function table(head: string[], rows: string[][]): string {
  if (rows.length === 0) return '_Nothing recorded yet._'
  const line1 = `| ${head.join(' | ')} |`
  const line2 = `| ${head.map(() => '---').join(' | ')} |`
  const body = rows.map((row) => `| ${row.map((cell) => String(cell).replace(/\|/g, '\\|')).join(' | ')} |`)
  return [line1, line2, ...body].join('\n')
}

const productName = (project: Project) => project.name || 'Untitled product'

/** The answers the builder gave to this step's questions, as prose. */
function answersSection(project: Project, role: RoleDef, step: RoleStep): string {
  if (step.questions.length === 0) return '_No clarifying questions on this step._'
  return step.questions
    .map((question, index) => {
      const answer = (project.answers ?? {})[answerKey(role.id, step.id, index)]?.trim()
      return `### ${question.question}\n\n${answer ? answer : '_Not answered yet._'}\n\n> Why it is asked: ${question.why}`
    })
    .join('\n\n')
}

/** Every documented decision on the project so far. */
function decisionsSection(project: Project, role: RoleDef): string {
  const rows = role.steps.map((step, index) => {
    const review = stepReview(project, role, step)
    const label = review
      ? review.decision === 'proceed-revisit'
        ? 'proceed — revisit'
        : review.decision
      : step.ready(project)
        ? 'ready, not reviewed'
        : 'not started'
    return [`${index + 1}. ${step.title}`, label, review?.note ?? '—']
  })
  return table(['Step', 'Review', 'Note'], rows)
}

function header(project: Project, role: RoleDef, step: RoleStep, index: number, kind: string): string {
  return `# ${productName(project)} — ${step.title} (${kind})

> **Role:** ${role.name} (${role.tag}) · **Process:** ${role.processLabel}
> **Step ${index + 1} of ${role.steps.length}:** ${step.title}
> Generated by ProdOps from the compiled project and the builder's answers. Where a value was not
> decided, this document says so instead of guessing.

**What this step decides.** ${step.decides}

**What it leaves behind.** ${step.produces.join(' · ')}`
}

/* ---------------------------------------------------------------- evidence -- */

/** The product's own data, quoted so a spec is checkable rather than asserted. */
function evidence(project: Project, step: RoleStep): string {
  const { brief, data, design, sections, flows, system, audit, roadmap } = project
  const blocks: string[] = []
  const wants = (...ids: string[]) => ids.includes(step.id)

  if (wants('vision-outcome', 'design-brief', 'charter', 'question')) {
    blocks.push(`**Summary.** ${brief.summary || '_No summary yet._'}`)
    if (brief.elevator) blocks.push(`**Elevator line.** ${brief.elevator}`)
    if (brief.metrics.length > 0) {
      blocks.push(`**Success measures.**\n${list(brief.metrics.map((m) => `**${m.label}** → ${m.target} — ${m.why}`))}`)
    }
  }

  if (wants('stakeholders', 'participants', 'research-plan', 'design-brief', 'charter')) {
    if (brief.personas.length > 0) {
      blocks.push(
        `**People.**\n${table(
          ['Persona', 'Role', 'Goal', 'Pain'],
          brief.personas.map((p) => [p.name, p.role, p.goal, p.pain]),
        )}`,
      )
    }
    if (brief.nonGoals.length > 0) blocks.push(`**Out of scope.**\n${list(brief.nonGoals)}`)
  }

  if (wants('current-state', 'synthesis', 'journey-map', 'metrics')) {
    if (brief.problems.length > 0) {
      blocks.push(
        `**Problems today.**\n${list(brief.problems.map((p) => `**${p.title}** — ${p.detail} (cost: ${p.cost})`))}`,
      )
    }
    if (brief.risks.length > 0) {
      blocks.push(`**Risks.**\n${list(brief.risks.map((r) => `${r.risk} → ${r.mitigation}`))}`)
    }
    if (brief.metrics.length > 0) {
      blocks.push(`**Measures.**\n${list(brief.metrics.map((m) => `${m.label} → ${m.target}`))}`)
    }
  }

  if (wants('requirements', 'section-specs', 'test-cases', 'plan', 'inventory', 'frontend', 'tests', 'handoff')) {
    if (sections.length > 0) {
      blocks.push(
        `**Sections and their requirements.**\n${table(
          ['Section', 'Purpose', 'Requirements', 'Must'],
          sections.map((s) => [
            s.name,
            s.purpose.slice(0, 90),
            String(s.requirements.length),
            String(s.requirements.filter((r) => r.priority === 'must').length),
          ]),
        )}`,
      )
    }
  }

  if (wants('prioritisation', 'schedule', 'opportunities', 'measurement')) {
    if (roadmap.phases.length > 0) {
      blocks.push(
        `**Roadmap.**\n${table(
          ['Phase', 'Horizon', 'Goal', 'Outcomes'],
          roadmap.phases.map((phase) => [phase.name, phase.horizon, phase.goal, phase.outcomes.join('; ')]),
        )}`,
      )
    }
    if (brief.differentiators.length > 0) {
      blocks.push(`**Differentiators.**\n${list(brief.differentiators.map((d) => `**${d.title}** — ${d.detail}`))}`)
    }
  }

  if (
    wants('solution-flows', 'touchpoints', 'blueprint', 'moments', 'opportunities', 'app-shell', 'layout', 'research-plan')
  ) {
    if (flows.length > 0) {
      blocks.push(
        `**Flows.**\n${table(
          ['Flow', 'Persona', 'Steps', 'Failure path'],
          flows.map((flow) => [flow.name, flow.persona, flow.steps.map((s) => s.title).join(' → '), flow.failure]),
        )}`,
      )
    }
    if (design.layout.nav.length > 0) {
      blocks.push(`**Shell navigation.** ${design.layout.nav.map((n) => `\`${n}\``).join(' · ')}`)
    }
  }

  if (wants('entities', 'fields-types', 'relationships', 'sources', 'model', 'backend', 'architecture', 'security')) {
    if (data.entities.length > 0) {
      blocks.push(
        `**Entities.**\n${table(
          ['Entity', 'Fields', 'Required', 'Rows'],
          data.entities.map((entity) => [
            entity.name,
            String(entity.fields.length),
            String(entity.fields.filter((f) => f.required).length),
            String(entity.rows.length),
          ]),
        )}`,
      )
    }
    if (data.relationships.length > 0) {
      blocks.push(
        `**Relationships.**\n${list(data.relationships.map((r) => `${r.from} ${r.kind} ${r.to} — ${r.label}`))}`,
      )
    }
  }

  if (wants('schema-constraints', 'sample-data', 'backend-contract')) {
    const tables = (data.sql.match(/create table/gi) ?? []).length
    blocks.push(
      tables > 0 ? `**Schema.** ${tables} tables generated from the data shape.` : '**Schema.** No schema generated yet.',
    )
    if (data.notes.length > 0) blocks.push(`**Data-layer notes.**\n${list(data.notes)}`)
  }

  if (wants('design-tokens', 'components', 'accessibility', 'visual-editor', 'design-brief', 'section-screens')) {
    blocks.push(
      `**Colour roles.**\n${table(
        ['Role', 'Base', 'On it', 'Why'],
        design.colors.map((c) => [c.role, c.base, c.contrastText, c.rationale]),
      )}`,
    )
    blocks.push(
      `**Type roles.**\n${list(design.typography.map((t) => `**${t.role}** ${t.family} ${t.size}/${t.lineHeight} — ${t.usage}`))}`,
    )
    if (project.designSource) {
      const source = project.designSource
      blocks.push(`**Design source.** ${source.label} (${source.kind})${source.url ? ` — ${source.url}` : ''}`)
    }
  }

  if (
    wants(
      'screens-shots',
      'prototype',
      'functional',
      'regression',
      'signoff',
      'review',
      'audit-coverage',
      'runbook',
      'status',
      'handoff',
      'pipeline',
    )
  ) {
    if (sections.length > 0) {
      blocks.push(
        `**Screens.**\n${table(
          ['Section', 'Screen', 'Route'],
          sections.flatMap((s) => s.screens.map((screen) => [s.name, screen.name, screen.route])),
        )}`,
      )
    }
    const pass = audit.checks.filter((c) => c.status === 'pass').length
    const warn = audit.checks.filter((c) => c.status === 'warn').length
    const fail = audit.checks.filter((c) => c.status === 'fail').length
    blocks.push(`**Audit.** ${audit.score}/100 · ${pass} pass · ${warn} warn · ${fail} fail`)
  }

  if (wants('architecture', 'environments', 'pipeline', 'observability', 'api-contract', 'backend-contract')) {
    if (system.stack.length > 0) {
      blocks.push(
        `**Stack.**\n${table(
          ['Layer', 'Choice', 'Why'],
          system.stack.map((s) => [s.layer, `${s.choice} ${s.version}`.trim(), s.reason]),
        )}`,
      )
    }
    blocks.push(`**Registry components.** ${system.components.map((c) => `\`${c.name}\``).join(' · ')}`)
  }

  if (wants('validation-handoff', 'handoff', 'signoff')) {
    blocks.push(
      `**Audit checks.**\n${table(
        ['Check', 'Status', 'Detail'],
        audit.checks.map((c) => [c.label, c.status, c.detail]),
      )}`,
    )
  }

  if (blocks.length === 0) {
    blocks.push(
      `**Brief.** ${brief.summary || '_No summary yet._'}`,
      `**Sections.** ${sections.map((s) => s.name).join(' · ') || '_none_'}`,
      `**Entities.** ${data.entities.map((e) => e.name).join(' · ') || '_none_'}`,
    )
  }

  return blocks.join('\n\n')
}

/* ---------------------------------------------------------------- builders -- */

function specBody(project: Project, role: RoleDef, step: RoleStep, index: number): string {
  const open =
    step.blockers(project).length > 0
      ? list(step.blockers(project).map((blocker) => `**Open** — ${blocker}`))
      : '- None. The artefacts this step needs are present.'

  return [
    header(project, role, step, index, 'spec'),
    `## Clarifying questions and answers\n\n${answersSection(project, role, step)}`,
    `## Decisions across the process\n\n${decisionsSection(project, role)}`,
    `## Evidence from the product\n\n${evidence(project, step)}`,
    `## Open items\n\n${open}`,
    `## Acceptance\n\n- [ ] The answers above reflect the builder's intent, not a default\n- [ ] The artefacts named for this step exist in the handoff\n- [ ] The next role can start from this document alone`,
  ].join('\n\n')
}

function processBody(project: Project, role: RoleDef, step: RoleStep, index: number, label: string): string {
  const { brief, data, flows, sections } = project

  if (step.id === 'current-state') {
    const rows = flows.flatMap((flow) =>
      flow.steps.map((s, i) => [String(i + 1), `${flow.name} — ${s.title}`, flow.persona, s.detail]),
    )
    return [
      header(project, role, step, index, label.toLowerCase()),
      `## The as-is process\n\nThese are the flows the product has compiled so far, read as the process that exists today.\n\n${table(
        ['#', 'Step today', 'Who does it', 'What happens'],
        rows,
      )}`,
      `## What it costs\n\n${list(brief.problems.map((p) => `**${p.title}** — ${p.detail} (cost: ${p.cost})`))}`,
      `## Risks in the current state\n\n${list(brief.risks.map((r) => `${r.risk} → ${r.mitigation}`))}`,
      `## Answers\n\n${answersSection(project, role, step)}`,
    ].join('\n\n')
  }

  if (step.id === 'journey-map') {
    const rows = flows.map((flow, i) => [
      `${i + 1}. ${flow.name}`,
      flow.steps.map((s) => s.title).join(' → '),
      flow.goal,
      flow.failure,
    ])
    return [
      header(project, role, step, index, label.toLowerCase()),
      `## Journey stages\n\n${table(['Stage', 'What the customer does', 'What they want', 'Where it breaks'], rows)}`,
      `## Who the journey is for\n\n${list(brief.personas.map((p) => `${p.name} — ${p.goal}`))}`,
      `## Answers\n\n${answersSection(project, role, step)}`,
    ].join('\n\n')
  }

  if (step.id === 'blueprint') {
    const front = flows.flatMap((flow) => flow.steps.map((s) => [flow.name, s.title, s.detail]))
    const back = data.entities.map((entity) => [entity.name, entity.description, entity.statusField ?? '—'])
    return [
      header(project, role, step, index, label.toLowerCase()),
      `## Front stage — what the customer sees\n\n${table(['Touchpoint', 'Customer action', 'What is promised'], front)}`,
      `## Back stage — what has to happen\n\n${table(['Entity', 'What happens', 'Owner'], back)}`,
      `## Fail points\n\n${list(brief.risks.map((r) => `${r.risk} → ${r.mitigation}`))}`,
      `## Answers\n\n${answersSection(project, role, step)}`,
    ].join('\n\n')
  }

  const flowTable = table(
    ['Flow', 'Persona', 'Steps'],
    flows.map((flow) => [flow.name, flow.persona, flow.steps.map((s) => s.title).join(' → ')]),
  )
  return [
    header(project, role, step, index, label.toLowerCase()),
    `## The process, start to finish\n\n${table(
      ['#', 'Step', 'Who owns it', 'What it leaves behind'],
      role.steps.map((s, i) => [String(i + 1), s.title, role.tag, s.produces[0] ?? '—']),
    )}`,
    `## Flows the product supports\n\n${flowTable}`,
    `## Sections in scope\n\n${list(sections.map((s) => `${s.name} — ${s.purpose}`))}`,
    `## Answers\n\n${answersSection(project, role, step)}`,
  ].join('\n\n')
}

function roadmapBody(project: Project, role: RoleDef, step: RoleStep, index: number, label: string): string {
  const { brief, roadmap } = project
  const rows = roadmap.phases.map((phase, i) => [
    String(i + 1),
    phase.name,
    phase.goal,
    phase.outcomes.join('; '),
    phase.horizon,
  ])

  return [
    header(project, role, step, index, label.toLowerCase()),
    `## Roadmap\n\n${table(['#', 'Phase', 'Goal', 'What ships', 'Horizon'], rows)}`,
    `## What makes this different\n\n${list(brief.differentiators.map((d) => `**${d.title}** — ${d.detail}`))}`,
    `## Out of scope, deliberately\n\n${list(brief.nonGoals)}`,
    `## Success measures\n\n${list(brief.metrics.map((m) => `${m.label} → ${m.target}`))}`,
    `## Sequencing note\n\n${roadmap.sequencingNote || '_None recorded._'}`,
    `## Answers\n\n${answersSection(project, role, step)}`,
  ].join('\n\n')
}

function visualBody(project: Project, role: RoleDef, step: RoleStep, index: number, label: string): string {
  const { design, sections } = project
  const swatches = design.colors
    .map(
      (c) =>
        `<div class="sw"><span style="background:${c.base};color:${c.contrastText}">Aa</span><b>${c.role}</b><code>${c.base}</code><small>text on it ${c.contrastText}</small></div>`,
    )
    .join('')
  const typeRows = design.typography
    .map((t) => `<tr><td>${t.role}</td><td>${t.family}</td><td>${t.size}/${t.lineHeight}</td><td>${t.usage}</td></tr>`)
    .join('')
  const screenRows = sections
    .flatMap((section) =>
      section.screens.map((screen) => `<tr><td>${section.name}</td><td>${screen.name}</td><td><code>${screen.route}</code></td></tr>`),
    )
    .join('')
  const radii = Object.entries(design.radii)
    .map(([key, value]) => `${key} ${value}px`)
    .join(', ')
  const spacing = design.spacing.map((s) => `${s.name} ${s.px}px`).join(' · ')

  return `<!doctype html>
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width,initial-scale=1">
<title>${productName(project)} — ${label}</title>
<style>
  :root { --ink:${design.colors[0]?.base ?? '#1c1917'}; --line:#e7e5e4; --muted:#78716c; }
  body { margin:0; padding:40px; font:15px/1.55 ${design.typography.find((t) => t.role === 'body')?.stack ?? 'ui-sans-serif, system-ui, sans-serif'}; color:var(--ink); background:#fff; }
  h1 { font-size:26px; margin:0 0 4px; letter-spacing:-.02em; }
  p.k { color:var(--muted); margin:0 0 28px; }
  h2 { font-size:12px; text-transform:uppercase; letter-spacing:.09em; color:var(--muted); margin:32px 0 12px; }
  .grid { display:grid; grid-template-columns:repeat(auto-fill,minmax(150px,1fr)); gap:12px; }
  .sw { border:1px solid var(--line); border-radius:10px; padding:10px; }
  .sw span { display:flex; align-items:center; justify-content:center; height:52px; border-radius:6px; margin-bottom:8px; font-weight:600; }
  .sw b { display:block; font-size:13px; } .sw code, .sw small { display:block; color:var(--muted); font-size:11px; }
  table { width:100%; border-collapse:collapse; font-size:13px; }
  th, td { text-align:left; padding:7px 10px; border-bottom:1px solid var(--line); }
  th { font-size:11px; text-transform:uppercase; letter-spacing:.07em; color:var(--muted); }
  footer { margin-top:40px; color:var(--muted); font-size:12px; }
</style>
</head>
<body>
<h1>${productName(project)}</h1>
<p class="k">${role.name} · step ${index + 1} of ${role.steps.length} · ${step.title} — ${label}</p>

<h2>Colour roles</h2>
<div class="grid">${swatches || '<p>No colour roles yet.</p>'}</div>

<h2>Type roles</h2>
<table><thead><tr><th>Role</th><th>Family</th><th>Size / line</th><th>Usage</th></tr></thead><tbody>${
    typeRows || '<tr><td colspan="4">No type roles yet.</td></tr>'
  }</tbody></table>

<h2>Screens</h2>
<table><thead><tr><th>Section</th><th>Screen</th><th>Route</th></tr></thead><tbody>${
    screenRows || '<tr><td colspan="3">No screens yet.</td></tr>'
  }</tbody></table>

<footer>Generated by ProdOps from the compiled project.${radii ? ` Radii: ${radii}.` : ''}${spacing ? ` Spacing: ${spacing}.` : ''}</footer>
</body>
</html>
`
}

/* ------------------------------------------------------------------- API -- */

/** What a single deliverable contains, ready to save or to export. */
export function renderDeliverable(project: Project, role: RoleDef, step: RoleStep, deliverable: Deliverable): string {
  const index = role.steps.findIndex((s) => s.id === step.id)
  switch (deliverable.kind) {
    case 'process':
      return processBody(project, role, step, index, deliverable.label)
    case 'roadmap':
      return roadmapBody(project, role, step, index, deliverable.label)
    case 'visual':
      return visualBody(project, role, step, index, deliverable.label)
    case 'markdown':
      return `${header(project, role, step, index, deliverable.label)}\n\n## Notes\n\n${
        (project.answers ?? {})[answerKey(role.id, step.id, 0)] || '_No notes yet._'
      }\n\n## Evidence\n\n${evidence(project, step)}\n`
    case 'spec':
    default:
      return `${specBody(project, role, step, index)}\n`
  }
}

/** One file per deliverable of one step. */
export function stepDocuments(
  project: Project,
  role: RoleDef,
  step: RoleStep,
): { deliverable: Deliverable; body: string }[] {
  return step.deliverables.map((deliverable) => ({ deliverable, body: renderDeliverable(project, role, step, deliverable) }))
}

/** The roles this project has engaged, primary first, without duplicates. */
export function projectRoleIds(project: Project): string[] {
  return Array.from(new Set([project.roleId, ...(project.roles ?? [])].filter((id): id is string => Boolean(id))))
}

/** Every document every engaged role defines, as handoff files (`spec/<role>/…`). */
export function roleSpecFiles(project: Project): { path: string; content: string }[] {
  const files: { path: string; content: string }[] = []
  for (const id of projectRoleIds(project)) {
    const role = roleById(id)
    if (!role) continue
    for (const step of role.steps) {
      for (const document of stepDocuments(project, role, step)) {
        files.push({ path: document.deliverable.file, content: document.body })
      }
    }
  }
  return files
}

/** The saved artifacts, as handoff files — the documents the builder actually saved. */
export function savedArtifactFiles(project: Project): { path: string; content: string }[] {
  return (project.artifacts ?? []).map((artifact) => ({ path: artifact.file, content: artifact.body }))
}

/** How many of a role's documents have been saved, for the rail and the export. */
export function artifactCoverage(project: Project, role: RoleDef): { saved: number; total: number } {
  const total = role.steps.reduce((count, step) => count + step.deliverables.length, 0)
  return { saved: roleArtifacts(project, role.id).length, total }
}
