import type { Project, Version } from '../types'
import { buildPackage, packageSizeKb } from '../export/package'
import { download } from './format'
import { slugify } from '../engine/rng'
import { buildWiki, versionsMarkdown } from './wiki'

export async function downloadWikiZip(project: Project, versions: Version[] = []): Promise<void> {
  const { default: JSZip } = await import('jszip')
  const zip = new JSZip()
  const root = zip.folder(`${slugify(project.name)}-wiki`)!
  for (const entry of buildWiki(project)) root.file(`${entry.slug}.md`, entry.body + '\n')
  root.file('CHANGELOG.md', versionsMarkdown(project, versions))
  const branches = Array.from(new Set(versions.map((v) => v.branch)))
  root.file(
    'README.md',
    `# ${project.name} — prototype wiki\n\nGenerated by Lula DevZign.\n\n${buildWiki(project)
      .map((e) => `- [${e.title}](./${e.slug}.md) — ${e.summary}`)
      .join('\n')}\n\n## Branches\n\n${(branches.length ? branches : ['main']).map((b) => `- \`${b}\``).join('\n')}\n\nKeep this folder next to the code and commit it with the prototype. One worktree per exploration keeps the wiki and the UI moving together:\n\n\`\`\`bash\ngit worktree add ../${project.id}-explore explorer\n\`\`\`\n`,
  )
  const blob = await zip.generateAsync({ type: 'blob', compression: 'DEFLATE' })
  download(`${slugify(project.name)}-wiki.zip`, blob, 'application/zip')
}

export async function downloadProjectZip(project: Project, versions: Version[] = []): Promise<void> {
  // Loaded on demand — keeps ~100KB of zip machinery out of the first paint.
  const { default: JSZip } = await import('jszip')
  const files = buildPackage(project, versions)
  const zip = new JSZip()
  const root = zip.folder(`${slugify(project.name)}-devzign`)!
  for (const file of files) root.file(file.path, file.content)
  const blob = await zip.generateAsync({ type: 'blob', compression: 'DEFLATE' })
  download(`${slugify(project.name)}-devzign.zip`, blob, 'application/zip')
}

export function packageSummary(project: Project, versions: Version[] = []): { files: number; kb: number } {
  const files = buildPackage(project, versions)
  return { files: files.length, kb: packageSizeKb(files) }
}
